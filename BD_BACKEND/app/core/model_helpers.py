"""Shared SQLAlchemy building blocks for model modules (UUID keys, timestamps, enum columns).

Needed so every module that defines tables (leads, imports, later compliance) declares keys,
timestamps and fixed-value columns the same way instead of copying the code; the model
modules import these helpers and the migrations mirror the result by hand.
"""

import enum
import uuid
from datetime import datetime

from sqlalchemy import CheckConstraint, DateTime, Enum, text
from sqlalchemy.orm import Mapped, declared_attr, mapped_column

from app.core.clock import now


def enum_column(enum_cls: type[enum.StrEnum]) -> Enum:
    """Map a StrEnum to a VARCHAR column that returns enum members.

    The CHECK is declared separately with in_check() so its name is explicit and the
    migration can mirror it.
    """
    return Enum(
        enum_cls,
        native_enum=False,
        create_constraint=False,
        length=max(len(member.value) for member in enum_cls),
        values_callable=lambda members: [member.value for member in members],
    )


def in_check(column: str, enum_cls: type[enum.StrEnum], name: str) -> CheckConstraint:
    """Build the named CHECK that limits a column to the values of a StrEnum."""
    # The values come from the enum definition, never from user input.
    allowed = ", ".join(f"'{member.value}'" for member in enum_cls)
    return CheckConstraint(f"{column} IN ({allowed})", name=name)


class TimestampMixin:
    """created_at / updated_at for tables whose rows change after creation.

    Time comes only from core.clock.now(), so there are no server-side defaults.
    """

    @declared_attr
    def created_at(cls) -> Mapped[datetime]:
        return mapped_column(DateTime(timezone=True), nullable=False, default=now)

    @declared_attr
    def updated_at(cls) -> Mapped[datetime]:
        return mapped_column(DateTime(timezone=True), nullable=False, default=now, onupdate=now)


def uuid_pk() -> Mapped[uuid.UUID]:
    """Primary key generated by the database (gen_random_uuid())."""
    return mapped_column(primary_key=True, server_default=text("gen_random_uuid()"))
