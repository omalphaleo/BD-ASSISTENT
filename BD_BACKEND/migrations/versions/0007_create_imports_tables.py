"""create the imports tables and link quarantine records to raw rows

Schema change: adds six `imports` tables (source_profiles, import_files, column_mappings,
raw_rows, import_reports, import_changes), a PL/pgSQL trigger that keeps raw_rows immutable,
and the nullable, unique quarantine_records.raw_row_id foreign key that 0006 left out.
Needed so M2 import can store every uploaded row exactly as received (D-099), remember the
mapping used per file (D-049), warn about re-uploaded files (D-109) and report what each
import did (D-050). Mirrors app.imports.models; tests/test_user_model.py fails if the models
and this schema drift.

Risks:
- Locking: the new tables are new objects. ALTER TABLE quarantine_records takes a brief
  ACCESS EXCLUSIVE lock to add the column and constraints; the column is nullable with no
  default, so no rows are rewritten.
- No data is inserted: source_profiles starts empty (the three layouts are not agreed yet).
- Immutability: the trigger rejects any UPDATE that changes id, import_file_id, row_number,
  original_values, email_normalized or created_at on raw_rows. person_id may change (release,
  merge, SET NULL when a person is deleted). DELETE stays allowed because erase-person removes
  rows (D-099). TRUNCATE is not guarded.
- Reversibility: downgrade() drops the trigger, the function, the quarantine link and all six
  tables, so every stored raw row, mapping, report and change summary is lost and cannot be
  restored (the quarantine column's links are lost too). It must run after any later migration
  that references these tables has been downgraded first.
- Not covered: created_at / updated_at have no database default (core.clock.now() supplies
  them in the app). import_files.status uses VARCHAR + CHECK, so adding a value later is a new
  migration that replaces the constraint.
- Never edit this migration after it is applied; further changes need a new migration.

Revision ID: 0007
Revises: 0006
Create Date: 2026-11-20
"""

