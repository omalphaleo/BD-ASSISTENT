"""create the compliance tables and seed the sending gate

Schema change: adds four `compliance` tables (opt_outs, compliance_gate_status,
compliance_checklist_items, erasure_records) and seeds one gate row plus the four D-081
checklist rows. Needed so M3 can enforce per-address opt-outs (D-066), M8 can refuse real
sending until the checklist passes (D-081), and erase-person can leave proof without personal
data (D-099). Mirrors app.compliance.models; tests/test_user_model.py fails if the models and
this schema drift. EligibilitySnapshot is not created (planned; no approved requirement).

Risks:
- Locking: all four tables are new objects; no existing table is altered.
- Data inserted: one compliance_gate_status row (real sending disabled) and four
  compliance_checklist_items rows (all not passed). Their created_at / updated_at use the
  database now() because migrations run outside the app and core.clock.now() is not available.
- Reversibility: downgrade() drops all four tables, so every stored opt-out, the gate state,
  the checklist progress and every erasure record are lost and cannot be restored. Dropping
  opt_outs would make previously opted-out addresses contactable again, so never downgrade
  past this revision on a database that holds real opt-outs. A later migration that
  references these tables must be downgraded first.
- Not covered: item_key and source use VARCHAR + CHECK, so adding a value later is a new
  migration that replaces the constraint (a fifth checklist item also needs a new seed row).
- Never edit this migration after it is applied; further changes need a new migration.

Revision ID: 0008
Revises: 0007
Create Date: 2026-11-20
"""

