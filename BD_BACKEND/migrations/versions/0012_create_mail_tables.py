"""create the mail tables (threads, outbox, inbound, delta cursors, classifications, bounces)

Schema change: adds six `mail` tables and the foreign key `outreach_messages.thread_id` ->
`mail_threads.id`. Needed so M5 can store the mock Outbox copy of every sent email, M6 can keep
matched replies with their classification and bounces (D-016, D-030, D-094, D-096) and M7 can
keep one Microsoft Graph delta cursor per mailbox. Mirrors app.mail.models;
tests/test_user_model.py fails if the models and this schema drift.

Risks:
- Locking: the six tables are new objects. The only existing table altered is
  `outreach_messages` (migration 0011): an index and a foreign key are added to `thread_id`,
  which holds no data yet because nothing queues messages before M5, so validation is instant.
  On a populated table the foreign key validation would scan it; none exists today.
- No data inserted.
- Reversibility: downgrade() first drops the new foreign key and index on `outreach_messages`,
  then the six tables, so every thread, mock outbox copy, stored reply, classification, cursor
  and bounce is lost and cannot be restored; `outreach_messages.thread_id` keeps its values but
  no longer points at anything. Never downgrade past this revision on a database holding real
  mail. A later migration that references these tables must be downgraded first.
- Not covered: fixed-value columns use VARCHAR + CHECK, so adding a category later is a new
  migration that replaces the constraint.
- Never edit this migration after it is applied; further changes need a new migration.

Revision ID: 0012
Revises: 0011
Create Date: 2026-11-24
"""

