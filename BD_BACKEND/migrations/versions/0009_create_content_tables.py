"""create the content tables (voice, profiles, knowledge base, embeddings, structures, versions)

Schema change: adds nine `content` tables (voice_settings, size_profiles, industry_profiles,
knowledge_items, knowledge_embeddings, industry_profile_items, email_structures,
structure_sections, config_versions). Needed so M4 can store the AI writing guidance (D-085),
the knowledge base and its pgvector embeddings (D-088) and the hybrid email structures
(D-084, D-112) with restorable version snapshots (D-112). Mirrors app.content.models;
tests/test_user_model.py fails if the models and this schema drift.

Risks:
- Locking: all nine tables are new objects; the only existing table referenced is `users`
  (foreign keys), which is not altered.
- Requires the pgvector extension created by revision 0001 (the vector(768) column).
- No data inserted: defaults for the voice, profiles and structures are seeded by M4.
- Reversibility: downgrade() drops all nine tables, so every knowledge item, embedding,
  profile, structure and version snapshot is lost and cannot be restored. Never downgrade
  past this revision on a database holding real content. A later migration that references
  these tables must be downgraded first.
- Not covered: fixed-value columns use VARCHAR + CHECK, so adding a value later is a new
  migration that replaces the constraint. Changing the 768-dimension vector size also needs a
  new migration (and re-embedding).
- Never edit this migration after it is applied; further changes need a new migration.

Revision ID: 0009
Revises: 0008
Create Date: 2026-11-23
"""

