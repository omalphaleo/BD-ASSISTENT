"""create the leads tables (companies, people and everything attached to them)

Schema change: adds 16 `leads` tables: companies, people, person_emails, person_phones,
social_profiles, contact_channels, quarantine_records, duplicate_candidates, merge_records,
segments, lead_notes, lead_events, touches, lead_status_flags, industry_mappings and
state_mappings. Needed so M2 import can write and merge unified lead records and M3 search,
lead detail and status flags can read them; lead data keeps the latest values only (D-008).
Mirrors app.leads.models; tests/test_user_model.py fails if the models and this schema drift.

Deliberately NOT created here (added by the migration that owns the other side):
- quarantine_records.raw_row_id and its unique foreign key: raw_rows is created in 0007.
- foreign keys on touches/lead_events campaign_id and outreach_message_id: the campaigns and
  outreach_messages tables are created in B's 0010 and 0011, which add the constraints. Until
  then those two columns are plain nullable UUIDs with no integrity check.

Risks:
- Locking: creates new objects only (plus foreign keys that read users), so nothing existing
  is locked or rewritten.
- No data is inserted: the mapping tables start empty; M2 seeds them (D-076, D-078).
- Reversibility: downgrade() drops all 16 tables, so every lead, address, note, flag and
  mapping stored in them is lost and cannot be restored. users is untouched. It must run
  after any later migration that references these tables has been downgraded first.
- Not covered: created_at / updated_at and the event times have no database default
  (core.clock.now() supplies them in the app), so a row inserted outside the app must supply
  them. Fixed-value columns use VARCHAR + CHECK, so adding a value later is a new migration
  that replaces the constraint.
- Never edit this migration after it is applied; further changes need a new migration.

Revision ID: 0006
Revises: 0005
Create Date: 2026-11-20
"""

